/**
 * Build the browser artifact.
 *
 * The bundle ships plain JavaScript (no bundler, no TSX), so this script
 * concatenates the sources in dependency order, strips their ESM import/export
 * syntax, and wraps the result in the Client module-loader envelope that the
 * Web app expects. Run `node build.mjs` after editing src/*.mjs.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const PACKAGE_ID = '@local/dsh-wechat-studio'

function stripModuleSyntax(source) {
  return source
    .split('\n')
    .filter(line => !/^\s*import\s+[^'"]*from\s+['"]/.test(line) && !/^\s*import\s+['"]/.test(line))
    .join('\n')
    .replace(/^export\s+/gm, '')
}

const sources = ['i18n', 'themes', 'fidelity', 'engine', 'render', 'docparse', 'images', 'docdb', 'bridge', 'ui-shell', 'ui-editor', 'ui-design', 'ui-misc']
  .map(name => {
    const code = stripModuleSyntax(readFileSync(join(root, 'src', `${name}.mjs`), 'utf8'))
    return `/* ===== src/${name}.mjs ===== */\n${code.trim()}\n`
  })
  .join('\n')

const bundle = `/**
 * Browser half of ${PACKAGE_ID}.
 * Generated by build.mjs from src/*.mjs. Do not edit by hand.
 */
window.__ModuleLoader__.load({
  id: '${PACKAGE_ID}',
  factory(require) {
    const React = require('react')
    const h = React.createElement

${sources}
/* ===== plugin entry ===== */

function panelLabel(ctx) {
  try {
    const locale = ctx.get('locale')
    const active = locale && typeof locale.getLocale === 'function' ? locale.getLocale().active : ''
    return /^zh/i.test(String(active)) ? '公众号排版' : 'WeChat studio'
  } catch {
    return 'WeChat studio'
  }
}

return {
  inject: ['slots'],
  apply(ctx) {
    bindUiLocale(() => {
      try {
        const locale = ctx.get('locale')
        return locale !== undefined && locale !== null && typeof locale.getLocale === 'function' ? locale.getLocale().active : ''
      } catch {
        return ''
      }
    })
    const label = () => panelLabel(ctx)
    ctx.effect(() => ctx.slots.inject('sidebar.panellist', () => ctx.slots.register({
      name: 'sidebar.panellist',
      id: PANEL_ID,
      order: 40,
      label,
    }, StudioSidebarIcon)), 'wechat-studio: sidebar entry')
    ctx.effect(() => ctx.slots.inject('main', () => ctx.slots.register({
      name: 'main',
      key: PANEL_ID,
    }, StudioPanel)), 'wechat-studio: studio panel')
  },
}
  },
})
`

writeFileSync(join(root, 'client.js'), bundle)
console.log(`client.js written: ${(Buffer.byteLength(bundle, 'utf8') / 1024).toFixed(1)} KiB`)
